test_that("templates are filled from data with figure formats", {
  d <- data.frame(k = 11, n = 12, p = 0.00146, q = 4.9e-4, x = -3.42, share = 51.2, big = 63921, txt = "a")
  expect_identical(FormatTemplate("{k|d}/{n|d} patients; p = {p|p}", d), "11/12 patients; p = 0.0015")
  expect_identical(FormatTemplate("q = {q|p}", d), "q = 4.9e-04")
  expect_identical(FormatTemplate("{x|sf1} ({share|f0}%); {big|comma}; {txt}", d), "−3.4 (51%); 63,921; a")
  expect_identical(FormatTemplate("{p|pfixed} {share|pfixed}", data.frame(p = 0.0039, share = 0.01953125)), "0.0039 0.020")
  expect_identical(FormatTemplate("{x|sf1}", data.frame(x = 0.02)), "0.0")
  expect_identical(FormatTemplate("n = {v|d}", data.frame(v = c(1, 2))), c("n = 1", "n = 2"))
  expect_identical(FormatTemplate(c("a {v|d}", "b {v|d}"), data.frame(v = c(1, 2))), c("a 1", "b 2"))
  expect_identical(FormatTemplate(c("a {v|d}", "b {v|d}"), data.frame(v = 5)), c("a 5", "b 5"))
  expect_identical(FormatTemplate("plain"), "plain")
  expect_identical(FormatTemplate("{v|p}", data.frame(v = NA_real_)), "n.e.")
  expect_error(FormatTemplate("{zz}", d), "missing column")
  expect_error(FormatTemplate("{txt|d}", d), "numeric")
  expect_error(FormatTemplate("{k|zz}", d), "Unknown template format")
  expect_error(FormatTemplate(c("a", "b", "c"), data.frame(v = 1:2)), "fewer rows")
})

test_that("quantile summaries use the linear (type 7) rule and keep group order", {
  d <- data.frame(type = rep(c("b", "a"), each = 4), x = 1, v = c(1, 2, 3, 10, 4, 4, NA, 8))
  q <- PlotDataQuantiles(d, c("type", "x"), "v")
  expect_identical(q$type, c("b", "a"))
  expect_equal(q$median, c(2.5, 4))
  expect_equal(q$lower, c(1.75, 4))
  expect_equal(q$upper, c(4.75, 6))
  expect_identical(q$n, c(4L, 3L))
  expect_error(PlotDataQuantiles(d, "type", "v", probs = 0.5), "same length")
})

test_that("joins keep row order and reject duplicated keys", {
  a <- data.frame(id = c("p2", "p1", "p3"), v = 1:3)
  b <- data.frame(id = c("p1", "p2"), group = c("A", "B"), w = c(10, 20))
  j <- PlotDataJoin(a, b, "id", columns = "group")
  expect_identical(j$group, c("B", "A", NA))
  expect_identical(names(PlotDataJoin(a, b, "id")), c("id", "v", "group", "w"))
  expect_identical(PlotDataJoin(a, b, "id", columns = "w", rename = "weight")$weight, c(20, 10, NA))
  expect_error(PlotDataJoin(a, rbind(b, b), "id"), "not unique")
})

test_that("ratios, pair ratios and pivots are computed per row", {
  r <- PlotDataRatio(data.frame(a = c(1, 0, 4), b = 2), "a", "b", log_base = 2)
  expect_equal(r$ratio, c(-1, -Inf, 1))
  expect_equal(PlotDataRatio(data.frame(a = 1, b = 3), "a", "b", pseudocount = 1, scale = 100)$ratio, 50)
  d <- data.frame(id = rep(c("p1", "p2", "p3"), c(2, 2, 1)), set = c("x", "ref", "x", "ref", "ref"),
                  v = c(4, 2, 1, 2, 5), w = c(1, 1, 3, 1, 1))
  pr <- PlotDataPairRatio(d, "id", "set", "x", "ref", c("v", "w"), names = c("V", "W"), log_base = 2)
  expect_identical(nrow(pr), 6L)
  expect_equal(pr$ratio[pr$variable == "V"], c(1, -1, NA))
  expect_equal(pr$ratio[pr$variable == "W"], c(0, log2(3), NA))
  expect_error(PlotDataPairRatio(rbind(d, d), "id", "set", "x", "ref", "v"), "not unique")
  w <- data.frame(type = c("a", "b"), `v|p1` = 1:2, `v|p2` = c(3, NA), check.names = FALSE)
  l <- PlotDataPivotLonger(w, "type", "^v\\|(.*)$", names_to = "unit")
  expect_identical(l$unit, c("p1", "p1", "p2"))
  expect_identical(l$value, c(1, 2, 3))
  expect_error(PlotDataPivotLonger(w, "type", "^zz"), "No column")
})

test_that("rows are filtered, flagged, summarised and collapsed", {
  d <- data.frame(id = c("a", "b", "c", "d"), n = c(1, 12, NA, 4), g = c("x", "y", "x", "x"))
  expect_identical(PlotDataWhere(d, list(list(column = "n", op = ">=", value = 10)))$id, "b")
  expect_identical(PlotDataWhere(d, list(column = "g", op = "in", value = c("y")))$id, "b")
  expect_identical(PlotDataWhere(d, list(list(column = "n", op = "is_na")))$id, "c")
  expect_identical(PlotDataWhere(d, list(list(column = "id", op = "not_matches", value = "^[ab]")))$id, c("c", "d"))
  expect_identical(PlotDataWhere(d, list(list(column = "g", op = "==", value = "x"), list(column = "n", op = "<", value = 2)))$id, "a")
  expect_error(PlotDataWhere(d, list(list(column = "n", op = "~", value = 1))), "Unknown operator")
  m <- PlotDataMembership(d, data.frame(id = c("b", "d")), "id", into = "excluded", negate = TRUE)
  expect_identical(m$excluded, c(TRUE, FALSE, TRUE, FALSE))
  expect_identical(PlotDataSummarise(d, "n", "sum")$n, 17)
  expect_identical(PlotDataSummarise(d, fun = "count", by = "g")$n, c(3L, 1L))
  expect_identical(PlotDataSummarise(d, "g", "n_distinct", into = "groups")$groups, 2L)
  expect_error(PlotDataSummarise(d, "n", "mode"), "Unknown summary")
  c1 <- PlotDataCollapse(d[c(4, 1), ], "{id}, {n|d}", order_by = "n", into = "few")
  expect_identical(c1$few, "a, 1; d, 4")
  expect_identical(c1$rows, 2L)
  expect_identical(PlotDataCollapse(d[0, ], "{id}")$text, "")
  expect_identical(PlotDataDirection(data.frame(n = c(9, 9), up = c(8, 1), e = c(0.5, -0.4)), "n", "up", "e")$k, c(8, 8))
  expect_identical(PlotDataConstant(data.frame(x = 1:2), "s", "a")$s, c("a", "a"))
  expect_identical(PlotDataUnite(data.frame(t = "a", r = c(20, 2.5)), c("t", "r"), "key")$key, c("a 20", "a 2.5"))
})

test_that("tables are bound and recoded", {
  b <- PlotDataBindRows(list(a = data.frame(x = 1), b = data.frame(y = 3, z = 2)), names_to = "src",
                        rename = list(b = c(x = "z")))
  expect_identical(names(b), c("x", "src", "y"))
  expect_identical(b$x, c(1, 2))
  expect_identical(b$y, c(NA, 3))
  expect_error(PlotDataBindRows(list(1)), "list of data frames")
  expect_identical(PlotDataBindColumns(list(data.frame(n = 9), data.frame(t = "a"))), data.frame(n = 9, t = "a"))
  expect_error(PlotDataBindColumns(list(data.frame(n = 1:2), data.frame(t = "a"))), "same number")
  r <- PlotDataRecode(data.frame(e = c("pct|B_cells", "density|B_cells", "x")), "e", map = c(x = "other"),
                      patterns = list(c("_", " "), c("^pct\\|(.*)$", "\\1 (% of cells)"), c("^density\\|(.*)$", "\\1 (per mm2)")),
                      into = "label")
